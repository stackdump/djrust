//! Loop sets: collections of loops cut from generated tracks, one genre each, to drop on a deck in
//! place of a whole track (djandroid's loop pads, beside its Acid Bass bank).
//!
//! A set is [`GROUPS`] groups, each one track of the genre (`TrackSpec::new(genre, seed,
//! "standard")`) as a deck plays it (`musicality::apply`: the pass that varies its bass figure,
//! harmony and drums by seed). The track's parts come in riffs, an A and a B per part (kick-0 …,
//! bass-0 …, melody-0 …, each instance a ring the sections switch between); a group's loops are
//! its two riffs with every part playing:
//!
//! - **A**: each part's A riff (its fullest instance) with the parts that have one riff only;
//! - **B**: each part's B riff (a part with no B keeps its A), then paired with A: the voices
//!   answer in A's gaps or an octave away, and never start a note against one of A's.
//!
//! Load a group's A on one deck and its B on the other and the crossfader swaps the answer in, as
//! with the Acid Bass bank, or play both at once: the two are **paired** ([`crate::looppair`]).
//! They share the key, the tempo and the length; the groove (kick, snare, bass, harmony) is the
//! same notes in both, so layered it stacks in unison; the voices (the melody, the arp) are
//! made to answer, B's notes falling in the gaps of A's, or an octave from them
//! ([`crate::looppair::complement`]). Without drums both play the tonal parts alone. Drum rings
//! are a bar (or half of one), the tonal ones 4 bars (blues: 12).
//!
//! Two kinds of set, one code path:
//!
//! - **Curated** ([`LoopSet::curated`]): the genre's own tempo and key, and track seeds picked by
//!   `examples/loopsets_curate.rs` (it scores every candidate with the musicality report, then
//!   keeps the cleanest that do not repeat each other) and written into [`CURATED`].
//! - **Generated** ([`LoopSet::generate`]): any `u32` seed. The seed picks a key (the genre's,
//!   moved -5…+6 semitones), a tempo (within 4 % of the genre's) and the groups' track seeds,
//!   drawn without scoring (scoring takes seconds on a phone; the curated sets are the scored
//!   ones), distinct within the set. Deterministic everywhere (`Mulberry32`, `libm`):
//!   the same genre and seed are the same set, loops and model CIDs on every platform, so a good
//!   one is kept and shared by its spec (`techno:4411`) or its [`LoopSet::cid`], as beats shares are.
//!
//! Pure (no I/O, `no_std + alloc`).

